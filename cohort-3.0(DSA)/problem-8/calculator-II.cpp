#include <iostream>
using namespace std;

int main() { 
    long long M;
    long long N;

    cin >> M >> N;

    cout << M << " + " << N << " = " << M + N << endl << endl;
    cout << M << " - " << N << " = " << M - N << endl << endl;
    cout << M << " * " << N << " = " << M * N << endl << endl;
    cout << M << " / " << N << " = " << M / N << endl << endl;
    cout << M << " % " << N << " = " << M % N << endl;
}