#include <iostream>
using namespace std;

int main() { 
    int M ;
    int N ;

    cin >> M >> N;

    cout << M << " + " << N << " = " << M + N << endl;
    cout << M << " - " << N << " = " << M - N << endl;
    cout << M << " * " << N << " = " << M * N << endl;
    cout << M << " / " << N << " = " << M / N << endl;
    cout << M << " % " << N << " = " << M % N << endl;
}